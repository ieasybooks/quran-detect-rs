//! Checks against `tests/fixtures/unicode-15.1.tsv`, generated from CPython 3.13.

use std::collections::HashMap;

use unicode_normalization::char::{canonical_combining_class, compose};

use crate::html::unescape_reference;
use crate::tables::{Class, UNICODE_VERSION};
use crate::text::wrappers;
use crate::unicode::{class, nfc, push_nfkc};

fn points(field: &str) -> Vec<char> {
    field
        .split_whitespace()
        .map(|hex| char::from_u32(u32::from_str_radix(hex, 16).unwrap()).unwrap())
        .collect()
}

fn fixture() -> HashMap<&'static str, Vec<Vec<String>>> {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/tests/fixtures/unicode-15.1.tsv"
    );
    let text: &'static str = std::fs::read_to_string(path).unwrap().leak();
    assert!(text.starts_with(&format!(
        "# Generated by scripts/generate-tables.py from Unicode {UNICODE_VERSION}."
    )));
    let mut sections: HashMap<&str, Vec<Vec<String>>> = HashMap::new();
    for line in text.lines().skip(1) {
        let mut fields = line.split('\t');
        let kind = fields.next().unwrap();
        sections
            .entry(kind)
            .or_default()
            .push(fields.map(str::to_owned).collect());
    }
    sections
}

fn assigned() -> impl Iterator<Item = char> {
    (0..=0x10_FFFF_u32)
        .filter_map(char::from_u32)
        .filter(|&c| class(c) != Class::Unassigned)
}

#[test]
fn single_character_normalization_matches_python_for_every_assigned_character() {
    let fixture = fixture();
    for (form, normalize) in [
        (
            "nfc",
            (|c: char| nfc(&[c]).chars().collect()) as fn(char) -> Vec<char>,
        ),
        ("nfkc", |c: char| {
            let mut out = Vec::new();
            push_nfkc(c, &mut out);
            out
        }),
    ] {
        let expected: HashMap<char, Vec<char>> = fixture[form]
            .iter()
            .map(|fields| (points(&fields[0])[0], points(&fields[1])))
            .collect();
        assert!(expected.len() > 1000, "{form}");
        for c in assigned() {
            let want = expected.get(&c).cloned().unwrap_or_else(|| vec![c]);
            assert_eq!(normalize(c), want, "{form} U+{:04X}", u32::from(c));
        }
    }
    // CPython leaves characters unassigned in 15.1 unchanged; so must the frozen guard.
    let unassigned = (0..=0x10_FFFF_u32)
        .filter_map(char::from_u32)
        .filter(|&c| class(c) == Class::Unassigned);
    for c in unassigned {
        let mut out = Vec::new();
        push_nfkc(c, &mut out);
        assert_eq!(out, [c], "U+{:04X}", u32::from(c));
    }
}

#[test]
fn combining_classes_and_compositions_match_python() {
    let fixture = fixture();
    let classes: HashMap<char, u8> = fixture["ccc"]
        .iter()
        .map(|fields| (points(&fields[0])[0], fields[1].parse().unwrap()))
        .collect();
    for c in assigned() {
        assert_eq!(
            canonical_combining_class(c),
            classes.get(&c).copied().unwrap_or(0),
            "U+{:04X}",
            u32::from(c)
        );
    }
    for fields in &fixture["compose"] {
        let (a, b) = (points(&fields[0])[0], points(&fields[1])[0]);
        let expected = (fields[2] != "-").then(|| points(&fields[2])[0]);
        assert_eq!(compose(a, b), expected, "{fields:?}");
    }
}

#[test]
fn reference_unescaping_matches_python() {
    let fixture = fixture();
    assert!(fixture["unescape"].len() > 2000);
    for fields in &fixture["unescape"] {
        let raw = points(&fields[0]);
        assert_eq!(wrappers(&raw), [(0, raw.len())], "{fields:?}");
        assert_eq!(unescape_reference(&raw), points(&fields[1]), "{fields:?}");
    }
}
