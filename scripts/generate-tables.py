#!/usr/bin/env python3
"""Generate frozen Unicode and HTML tables plus their verification fixtures.

Run with CPython 3.13 (Unicode 15.1.0) from the repository root:

    python3 -I scripts/generate-tables.py

The matcher classifies characters exactly as CPython 3.13 does. These tables
freeze that behavior, so later Unicode releases cannot silently change which
characters are Arabic letters, marks, barriers or whitespace. The fixture lets
`cargo test` check normalization data from the unicode-normalization crate
against the same Unicode version, for every character assigned in 15.1.
"""

from __future__ import annotations

import html
import html.entities
import re
import sys
import unicodedata
from pathlib import Path

UNICODE_VERSION = "15.1.0"
ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "crates/quran-detect/src/tables.rs"
FIXTURE = ROOT / "crates/quran-detect/tests/fixtures/unicode-15.1.tsv"

if sys.version_info[:2] != (3, 13) or unicodedata.unidata_version != UNICODE_VERSION:
    raise SystemExit(
        f"Use CPython 3.13 with Unicode {UNICODE_VERSION}; found "
        f"{sys.version.split()[0]} with Unicode {unicodedata.unidata_version}"
    )


def char_class(cp: int) -> str:
    char = chr(cp)
    category = unicodedata.category(char)
    if category == "Cn":
        return "Unassigned"
    if category[0] == "M":
        return "Mark"
    if category[0] == "L":
        return "ArabicLetter" if "ARABIC" in unicodedata.name(char, "") else "OtherLetter"
    if category[0] in "NS":
        return "NumberOrSymbol"
    return "Other"


def rust_string(text: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):04x}}}" for c in text) + '"'


def hex_points(text: str) -> str:
    return " ".join(f"{ord(c):04X}" for c in text)


def class_ranges() -> list[tuple[int, str]]:
    ranges: list[tuple[int, str]] = []
    for cp in range(0x110000):
        current = char_class(cp)
        if not ranges or ranges[-1][1] != current:
            ranges.append((cp, current))
    return ranges


def write_tables() -> None:
    ranges = class_ranges()
    spaces = [cp for cp in range(0x110000) if chr(cp).isspace()]
    entities = sorted(html.entities.html5.items())
    invalid_charrefs = sorted(html._invalid_charrefs.items())  # noqa: SLF001
    invalid_codepoints = sorted(html._invalid_codepoints)  # noqa: SLF001
    for value in dict(invalid_charrefs).values():
        assert len(value) == 1
    lines = [
        "//! Generated by `scripts/generate-tables.py` from CPython 3.13 (Unicode 15.1.0).",
        "//! Do not edit by hand; regenerate and review the diff instead.",
        "",
        "// Generated data is easier to audit as one value per line.",
        "#![allow(clippy::unreadable_literal)]",
        "",
        "/// Unicode version whose character data the tables reproduce.",
        "#[cfg(test)]",
        f'pub(crate) const UNICODE_VERSION: &str = "{UNICODE_VERSION}";',
        "",
        "/// Character classes used by tokenization, from general category and name.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub(crate) enum Class {",
        "    /// General category `Cn`.",
        "    Unassigned,",
        "    /// General categories `Mn`, `Mc` and `Me`.",
        "    Mark,",
        "    /// A letter whose Unicode name contains `ARABIC`.",
        "    ArabicLetter,",
        "    /// Any other letter.",
        "    OtherLetter,",
        "    /// Numbers and symbols.",
        "    NumberOrSymbol,",
        "    /// Punctuation, separators, controls, format, private-use and surrogate code points.",
        "    Other,",
        "}",
        "",
        "/// Sorted starts of ranges; each class applies up to the next start.",
        "#[rustfmt::skip]",
        "pub(crate) static CLASS_RANGES: &[(u32, Class)] = &[",
    ]
    lines += [f"    (0x{cp:06X}, Class::{name})," for cp, name in ranges]
    lines += [
        "];",
        "",
        "/// Code points for which CPython's `str.isspace()` is true.",
        "#[rustfmt::skip]",
        "pub(crate) static SPACES: &[u32] = &[",
    ]
    lines += [f"    0x{cp:04X}," for cp in spaces]
    lines += [
        "];",
        "",
        "/// HTML5 named character references from CPython's `html.entities.html5`, sorted by name.",
        "#[rustfmt::skip]",
        "pub(crate) static ENTITIES: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{name}", {rust_string(value)}),' for name, value in entities]
    lines += [
        "];",
        "",
        "/// Numeric references that HTML5 replaces with another character.",
        "#[rustfmt::skip]",
        "pub(crate) static INVALID_CHARREFS: &[(u32, char)] = &[",
    ]
    lines += [f"    (0x{num:02X}, '\\u{{{ord(value):04x}}}')," for num, value in invalid_charrefs]
    lines += [
        "];",
        "",
        "/// Numeric references that HTML5 removes.",
        "#[rustfmt::skip]",
        "pub(crate) static INVALID_CODEPOINTS: &[u32] = &[",
    ]
    lines += [f"    0x{cp:04X}," for cp in invalid_codepoints]
    lines += ["];", ""]
    TABLES.write_text("\n".join(lines), encoding="utf-8")


def unescape_cases() -> list[str]:
    """References shaped like the tokenizer's wrapper pattern, the only unescape input."""
    names = sorted(name for name in html.entities.html5 if re.fullmatch(r"[A-Za-z]+;?", name))
    cases = [f"&{name}" if name.endswith(";") else f"&{name};" for name in names]
    cases += [f"&{name.rstrip(';')}x;" for name in names[::7]]
    cases += [
        "&notit;", "&ampxyz;", "&amp;", "&AMP;", "&nosuchentity;", "&a;", "&ab;",
        "&" + "a" * 31 + ";", "&" + "a" * 32 + ";", "&" + "a" * 33 + ";",
        "&amp" + "x" * 40 + ";", "&lt" + "y" * 31 + ";", "&notin" + "z" * 30 + ";",
    ]
    numbers = [
        0, 1, 8, 9, 10, 11, 12, 13, 14, 31, 32, 38, 60, 127, 128, 129, 141, 143, 144, 157,
        159, 160, 1576, 1610, 0xD7FF, 0xD800, 0xDFFF, 0xE000, 0xFDCF, 0xFDD0, 0xFDEF,
        0xFDF0, 0xFFFD, 0xFFFE, 0xFFFF, 0x10000, 0x1FFFE, 0x10FFFD, 0x10FFFE, 0x10FFFF,
        0x110000, 2**31, 2**32, 2**64 + 5,
    ]
    for number in numbers:
        cases += [f"&#{number};", f"&#x{number:x};", f"&#x{number:X};", f"&#000{number};"]
    cases += ["&#" + "9" * 40 + ";", "&#x" + "F" * 40 + ";", "&#" + "0" * 50 + "65;"]
    return cases


def normalization_fixture() -> list[str]:
    lines = [f"# Generated by scripts/generate-tables.py from Unicode {UNICODE_VERSION}."]
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or unicodedata.category(chr(cp)) == "Cn":
            continue
        char = chr(cp)
        for form in ("NFC", "NFKC"):
            normalized = unicodedata.normalize(form, char)
            if normalized != char:
                lines.append(f"{form.lower()}\t{cp:04X}\t{hex_points(normalized)}")
        combining = unicodedata.combining(char)
        if combining:
            lines.append(f"ccc\t{cp:04X}\t{combining}")
        decomposition = unicodedata.decomposition(char)
        if decomposition and not decomposition.startswith("<"):
            parts = [int(part, 16) for part in decomposition.split()]
            if len(parts) == 2:
                pair = chr(parts[0]) + chr(parts[1])
                composed = unicodedata.normalize("NFC", pair)
                result = f"{ord(composed):04X}" if len(composed) == 1 else "-"
                lines.append(f"compose\t{parts[0]:04X}\t{parts[1]:04X}\t{result}")
    wrapper = re.compile(r"&(?:#[0-9]+|#x[0-9a-fA-F]+|[A-Za-z]+);")
    for case in unescape_cases():
        assert wrapper.fullmatch(case), case
        lines.append(f"unescape\t{hex_points(case)}\t{hex_points(html.unescape(case))}")
    return lines


def main() -> None:
    write_tables()
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text("\n".join(normalization_fixture()) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
